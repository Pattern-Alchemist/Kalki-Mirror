count_inserted = 0
count_skipped = 0
for lesson_id, hi_content in HI.items():
    anchor = f"id: '{lesson_id}',"
    idx = src.find(anchor)
    if idx == -1:
        print(f"SKIP (not found): {lesson_id}")
        count_skipped += 1
        continue

    # Find the next `evidence:` after this anchor
    ev_idx = src.find('evidence:', idx + len(anchor))
    if ev_idx == -1:
        print(f"SKIP (no evidence after {lesson_id}): {lesson_id}")
        count_skipped += 1
        continue

    block = src[idx:ev_idx]
    if 'hi: {' in block:
        print(f"SKIP (already has hi): {lesson_id}")
        count_skipped += 1
        continue

    # Find the indent of the evidence line
    line_start = src.rfind('\n', 0, ev_idx) + 1
    indent_match = re.match(r'^(\s+)', src[line_start:ev_idx])
    indent = indent_match.group(1) if indent_match else '        '

    # Escape single quotes in the hi content
    escaped = hi_content.replace("\\", "\\\\").replace("'", "\\'")
    hi_block = f"\n{indent}hi: {{ content: '{escaped}' }},\n"

    # Insert before the evidence line
    src = src[:line_start] + hi_block + src[line_start:]
    print(f"OK   : {lesson_id}")
    count_inserted += 1

with open(PATH, 'w', encoding='utf-8') as f:
    f.write(src)

print(f"\ninserted: {count_inserted}, skipped: {count_skipped}")
print(f"Remaining: {54 - count_inserted} lessons (46 of 54 follow the same pattern)")
