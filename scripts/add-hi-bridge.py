# 1) interface: add the optional hi field (EN fallback stays the corpus default)
old_iface = """export interface GlossaryEntry {
  term: string;
  sanskrit?: string;
  pronunciation?: string;
  definition: string;"""
new_iface = """export interface GlossaryEntry {
  term: string;
  sanskrit?: string;
  pronunciation?: string;
  definition: string;
  /**
   * Vol. 4 #13 — the hi corpus bridge. Optional Hindi (sadhu register)
   * fields with EN fallback: when the seeker's locale is hi and a term
   * carries a translation, the renderer shows it; otherwise the EN
   * definition serves unchanged. Scale beyond the top-20 stays
   * founder-review (the sadhu register is not to be machine-diluted).
   */
  hi?: {
    definition: string;
  };"""
assert src.count(old_iface) == 1, "interface anchor not unique"
src = src.replace(old_iface, new_iface)

# 2) per-entry hi blocks before each category line
inserted = 0
for term, hi_text in HI.items():
    anchor = f"term: '{term}',"
    first = src.find(anchor)
    if first == -1:
        print(f"FATAL: term anchor not found: {term}", file=sys.stderr)
        sys.exit(1)
    if src.find(anchor, first + 1) != -1:
        print(f"FATAL: term anchor not unique: {term}", file=sys.stderr)
        sys.exit(1)
    cat_off = src.find("category:", first)
    if cat_off == -1:
        print(f"FATAL: no category line after {term}", file=sys.stderr)
        sys.exit(1)
    if "hi:" in src[first:cat_off]:
        print(f"SKIP: {term} already carries hi", file=sys.stderr)
        continue
    indent = "    "
    block = (
        f"{indent}hi: {{\n"
        f"{indent}  definition:\n"
        f"{indent}    '{hi_text}',\n"
        f"{indent}}},\n"
    )
    src = src[:cat_off] + block + src[cat_off:]
    inserted += 1

open(PATH, 'w', encoding='utf-8').write(src)
print(f"OK: hi bridge inserted for {inserted} terms (of {len(HI)}), interface extended")
